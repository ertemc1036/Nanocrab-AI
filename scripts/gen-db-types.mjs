#!/usr/bin/env node
// Generates src/lib/supabase/database.types.ts from a migrated PostgreSQL
// database (DATABASE_URL), in the shape produced by `supabase gen types`.
// Run via: npm run db:types
import { writeFileSync } from "node:fs"
import pg from "pg"

const client = new pg.Client({ connectionString: process.env.DATABASE_URL })
await client.connect()

const TS = {
  uuid: "string",
  text: "string",
  date: "string",
  "timestamp with time zone": "string",
  integer: "number",
  smallint: "number",
  bigint: "number",
  numeric: "number",
  boolean: "boolean",
  jsonb: "Json",
  json: "Json",
  "character varying": "string",
}
const tsType = (dataType, udt) =>
  dataType === "ARRAY"
    ? `${TS[udt.replace(/^_/, "") === "text" ? "text" : udt.replace(/^_/, "")] ?? "unknown"}[]`
    : (TS[dataType] ?? "unknown")

const { rows: cols } = await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable,
         c.column_default, c.is_identity, c.ordinal_position
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`)

const { rows: fks } = await client.query(`
  select con.conname, cl.relname as table_name, rcl.relname as ref_table,
    array(select a.attname::text from unnest(con.conkey) with ordinality k(n, o)
          join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.o) as cols,
    array(select a.attname::text from unnest(con.confkey) with ordinality k(n, o)
          join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.o) as ref_cols
  from pg_constraint con
  join pg_class cl on cl.oid = con.conrelid join pg_namespace n on n.oid = cl.relnamespace
  join pg_class rcl on rcl.oid = con.confrelid join pg_namespace rn on rn.oid = rcl.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
  order by con.conname`)

const { rows: fns } = await client.query(`
  select p.proname, pg_get_function_identity_arguments(p.oid) as identity_args,
         p.proargnames::text[] as proargnames, p.proargmodes::text[] as proargmodes, p.pronargdefaults,
         array(select format_type(t, null) from unnest(p.proargtypes) t) as in_types,
         format_type(p.prorettype, null) as ret, p.proretset,
         array(select format_type(t, null) from unnest(p.proallargtypes) t) as all_types
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and format_type(p.prorettype, null) <> 'trigger'
  order by p.proname`)
await client.end()

const tables = {}
for (const c of cols) (tables[c.table_name] ??= []).push(c)

const out = [
  "// GENERATED by scripts/gen-db-types.mjs from supabase/migrations — do not edit.",
  "// Regenerate with: npm run db:types",
  "",
  "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]",
  "",
  "export type Database = {",
  "  __InternalSupabase: {",
  '    PostgrestVersion: "13.0.5"',
  "  }",
  "  public: {",
  "    Tables: {",
]
for (const [table, columns] of Object.entries(tables)) {
  const t = (c) =>
    tsType(c.data_type, c.udt_name) + (c.is_nullable === "YES" ? " | null" : "")
  out.push(`      ${table}: {`, "        Row: {")
  for (const c of columns) out.push(`          ${c.column_name}: ${t(c)}`)
  out.push("        }", "        Insert: {")
  for (const c of columns) {
    if (c.is_identity === "YES") {
      out.push(`          ${c.column_name}?: never`)
      continue
    }
    const optional = c.is_nullable === "YES" || c.column_default !== null
    out.push(`          ${c.column_name}${optional ? "?" : ""}: ${t(c)}`)
  }
  out.push("        }", "        Update: {")
  for (const c of columns) {
    out.push(`          ${c.column_name}?: ${c.is_identity === "YES" ? "never" : t(c)}`)
  }
  out.push("        }", "        Relationships: [")
  for (const fk of fks.filter((f) => f.table_name === table)) {
    out.push(
      "          {",
      `            foreignKeyName: "${fk.conname}"`,
      `            columns: [${fk.cols.map((x) => `"${x}"`).join(", ")}]`,
      "            isOneToOne: false",
      `            referencedRelation: "${fk.ref_table}"`,
      `            referencedColumns: [${fk.ref_cols.map((x) => `"${x}"`).join(", ")}]`,
      "          },"
    )
  }
  out.push("        ]", "      }")
}
out.push(
  "    }",
  "    Views: {",
  "      [_ in never]: never",
  "    }",
  "    Functions: {"
)

const pgToTs = (type) =>
  ({
    uuid: "string",
    text: "string",
    integer: "number",
    bigint: "number",
    boolean: "boolean",
    jsonb: "Json",
    void: "undefined",
    numeric: "number",
  })[type] ?? "unknown"
for (const f of fns) {
  const names = f.proargnames ?? []
  const modes = f.proargmodes ?? []
  const inputs = []
  const outputs = []
  names.forEach((name, i) => {
    const mode = modes[i] ?? "i"
    const type = (f.all_types?.length ? f.all_types : f.in_types)[i]
    if (mode === "i") inputs.push({ name, type })
    else if (mode === "t" || mode === "o") outputs.push({ name, type })
  })
  const firstDefault = inputs.length - f.pronargdefaults
  out.push(`      ${f.proname}: {`)
  out.push(inputs.length ? "        Args: {" : "        Args: never")
  if (inputs.length) {
    inputs.forEach((a, i) =>
      out.push(`          ${a.name}${i >= firstDefault ? "?" : ""}: ${pgToTs(a.type)}`)
    )
    out.push("        }")
  }
  if (outputs.length) {
    out.push("        Returns: {")
    for (const o of outputs) out.push(`          ${o.name}: ${pgToTs(o.type)}`)
    out.push(`        }${f.proretset ? "[]" : ""}`)
  } else {
    out.push(`        Returns: ${pgToTs(f.ret)}${f.proretset ? "[]" : ""}`)
  }
  out.push("      }")
}
out.push(
  "    }",
  "    Enums: {",
  "      [_ in never]: never",
  "    }",
  "    CompositeTypes: {",
  "      [_ in never]: never",
  "    }",
  "  }",
  "}",
  "",
  'type PublicSchema = Database["public"]',
  "",
  'export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]',
  'export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]',
  'export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]',
  ""
)
writeFileSync("src/lib/supabase/database.types.ts", out.join("\n"))
console.log(
  `Wrote types for ${Object.keys(tables).length} tables and ${fns.length} functions.`
)
