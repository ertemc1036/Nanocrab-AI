/** Generates a full plan as a DRAFT. It only becomes active if the founder approves it. */
export async function generatePlanAction(): Promise<ActionResult> {
  await requireUser()
  const scope = await requireWorkspaceScope()
  try {
    const plan = await runStructuredTask({
      scope,
      kind: "plan_generation",
      schema: generatedPlanSchema,
      schemaName: "business_plan",
      maxOutputTokens: 6000,
      task: [
        "Draft a complete, realistic business plan for the founder's current business, using only the workspace data above.",
        "Fit it to their real budget, weekly hours, skills and country. Keep each section concise and concrete (roughly 60–180 words).",
        "Do not invent statistics, market sizes, prices paid by customers, competitor facts or revenue projections. Where something is unknown, say how to find out.",
        "List every claim that still needs real-world validation in `assumptions` (short, testable statements).",
        "The first customer acquisition plan must be a step-by-step plan the founder can start this week.",
        "Write in the language the founder uses in their profile and business description.",
      ].join("\n"),
    })
    await createPlanVersion(
      plan,
      {
        status: "draft",
        source: "ai",
        note: "Draft generated by NanoCrab — review before activating",
      },
      scope
    )
  } catch (error) {
    return {
      ok: false,
      message:
        error instanceof AIError
          ? error.userMessage
          : "Couldn't generate a plan. Please try again.",
    }
  }
  refresh()
  return { ok: true, message: "Draft ready for your review." }
}

/** Asks NanoCrab to improve one section; the result is a proposal to approve. */
export async function improveSectionAction(
  section: string,
  instruction: string
): Promise<ActionResult> {
  await requireUser()
  const parsed = improveSectionInputSchema.safeParse({ section, instruction })
  if (!parsed.success) return { ok: false, message: parsed.error.issues[0]?.message }
  const scope = await requireWorkspaceScope()
  try {
    const result = await runStructuredTask({
      scope,
      kind: "plan_section",
      schema: improvedSectionSchema,
      schemaName: "improved_plan_section",
      maxOutputTokens: 1500,
      task: [
        `Improve the "${label(parsed.data.section)}" section of the active business plan.`,
        parsed.data.instruction
          ? `The founder asks: ${JSON.stringify(parsed.data.instruction)}`
          : "Make it more specific, realistic and actionable.",
        "Keep facts the founder provided. Don't invent data; mark claims that need validating in `assumptions`.",
        "Return the full replacement text for this section in `content`, and a short `rationale`.",
      ].join("\n"),
    })
    const rationale = [
      result.rationale,
      result.assumptions.length
        ? `Assumptions to validate: ${result.assumptions.join("; ")}`
        : "",
    ]
      .filter(Boolean)
      .join(" ")
      .slice(0, 600)
    await createProposals(
      [
        {
          kind: "plan_section",
          payload: { section: parsed.data.section, content: result.content, rationale },
        },
      ],
      null,
      scope
    )
  } catch (error) {
    return {
      ok: false,
      message:
        error instanceof AIError
          ? error.userMessage
          : "Couldn't improve this section. Please try again.",
    }
  }
  refresh()
  return { ok: true, message: "Suggestion ready — review it below the section." }
}

export async function activatePlanAction(planId: string): Promise<ActionResult> {
  await requireUser()
  const id = uuidSchema.safeParse(planId)
  if (!id.success) return { ok: false, message: "Version not found." }
  try {
    await activatePlanVersion(id.data)
  } catch {
    return { ok: false, message: "Couldn't activate this version." }
  }
  refresh()
  return { ok: true, message: "This version is now your active plan." }
}

export async function discardDraftAction(planId: string): Promise<ActionResult> {
  await requireUser()
  const id = uuidSchema.safeParse(planId)
  if (!id.success) return { ok: false, message: "Draft not found." }
  try {
    await discardDraft(id.data)
  } catch {
    return { ok: false, message: "Couldn't discard this draft." }
  }
  refresh()
  return { ok: true, message: "Draft discarded (kept in history)." }
}

export async function createMilestoneAction(
  _prev: FormState,
  formData: FormData
): Promise<FormState> {
  await requireUser()
  const input = {
    title: String(formData.get("title") ?? ""),
    description: "",
    targetDate: String(formData.get("targetDate") ?? ""),
  }
  const parsed = milestoneInputSchema.safeParse(input)
  if (!parsed.success)
    return { status: "error", fieldErrors: fieldErrorsFrom(parsed.error), values: input }
  try {
    await createMilestone(parsed.data)
  } catch {
    return { status: "error", message: "Couldn't add the milestone.", values: input }
  }
  refresh()
  return { status: "success", message: "Milestone added." }
}

export async function toggleMilestoneAction(
  id: string,
  achieved: boolean
): Promise<ActionResult> {
  await requireUser()
  const parsed = uuidSchema.safeParse(id)
  if (!parsed.success) return { ok: false }
  try {
    await setMilestoneAchieved(parsed.data, achieved)
  } catch {
    return { ok: false, message: "Couldn't update the milestone." }
  }
  refresh()
  return { ok: true }
}

