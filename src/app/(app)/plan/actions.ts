export type ActionResult = { ok: boolean; message?: string }

const label = (key: string) => PLAN_SECTIONS.find((s) => s.key === key)?.label ?? key

/** Saves one section as a new active version (versions are immutable). */
export async function savePlanSectionAction(
  section: string,
  content: string
): Promise<ActionResult> {
  await requireUser()
  const parsed = planSectionInputSchema.safeParse({ section, content })
  if (!parsed.success) return { ok: false, message: parsed.error.issues[0]?.message }
  const scope = await requireWorkspaceScope()
  try {
    const active = await getActivePlan(scope)
    await createPlanVersion(
      { ...(active?.sections ?? EMPTY_PLAN), [parsed.data.section]: parsed.data.content },
      { status: "active", source: "user", note: `Edited ${label(parsed.data.section)}` },
      scope
    )
  } catch {
    return { ok: false, message: "Couldn't save this section. Please try again." }
  }
  refresh()
  return { ok: true, message: "Saved as a new version." }
}

