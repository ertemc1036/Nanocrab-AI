import Link from "next/link"
import {
  ArrowRightIcon,
  CalendarClockIcon,
  CrosshairIcon,
  FlagIcon,
  OctagonAlertIcon,
  ZapIcon,
} from "lucide-react"
import type { ReactNode } from "react"

import { Button } from "@/components/ui/button"
import type {
  AccountabilityReport,
  CeoDirective,
} from "@/lib/nanocrab-ceo/accountability"
import type { BusinessTask } from "@/lib/nanocrab-ceo/types"
import { cn } from "@/lib/utils"

function formatDay(day: string): string {
  return new Intl.DateTimeFormat("en", {
    dateStyle: "medium",
    timeZone: "UTC",
  }).format(new Date(`${day}T00:00:00Z`))
}

function deadlineLabel(task: BusinessTask, today: string): string {
  if (!task.dueDate) return "No deadline set — agree one with your AI CEO"
  if (task.dueDate < today) return `Overdue since ${formatDay(task.dueDate)}`
  if (task.dueDate === today) return "Due today"
  return `Due ${formatDay(task.dueDate)}`
}

/** Today's CEO directive plus the facts behind it. Computed from stored data only. */
export function CeoDirectiveCard({
  directive,
  report,
  focusTask,
  executive,
  className,
}: {
  directive: CeoDirective
  report: AccountabilityReport
  focusTask: BusinessTask | null
  executive: boolean
  className?: string
}) {
  const urgent = directive.kind === "overdue" || directive.kind === "blocked"
  return (
    <section
      aria-labelledby="ceo-directive"
      className={cn(
        "flex flex-col rounded-2xl border bg-card p-6",
        urgent && "border-primary/40",
        className
      )}
    >
      <div className="flex flex-wrap items-center justify-between gap-2">
        <p className="flex items-center gap-2 text-xs font-medium tracking-wide text-primary uppercase">
          <CrosshairIcon className="size-3.5" />
          Today&apos;s CEO directive
        </p>
        <div className="flex items-center gap-2">
          <Link
            href="/settings#leadership"
            className={cn(
              "flex items-center gap-1 rounded-full border px-2 py-0.5 text-[11px]",
              executive ? "border-primary/40 text-primary" : "text-muted-foreground"
            )}
          >
            <ZapIcon className="size-3" />
            {executive ? "Executive Mode" : "Standard CEO"}
          </Link>
          <span
            className="rounded-full border px-2 py-0.5 text-[11px] text-muted-foreground"
            title="Computed from your tasks and milestones, not generated by AI"
          >
            From your data
          </span>
        </div>
      </div>

      <h2
        id="ceo-directive"
        className="mt-4 text-xl font-semibold tracking-tight text-balance"
      >
        {directive.headline}
      </h2>
      <p className="mt-2 max-w-xl text-sm leading-relaxed text-muted-foreground">
        {directive.detail}
      </p>

      <dl className="mt-5 grid gap-4 text-sm sm:grid-cols-2">
        <Fact icon={<CrosshairIcon />} label="Most important open task">
          {focusTask ? (
            <>
              <span className="font-medium">{focusTask.title}</span>
              <span className="block text-xs text-muted-foreground">
                {deadlineLabel(focusTask, report.today)}
              </span>
              {focusTask.successCriteria ? (
                <span className="block text-xs text-muted-foreground">
                  Done when: {focusTask.successCriteria}
                </span>
              ) : null}
            </>
          ) : report.open > 0 ? (
            <span className="text-muted-foreground">All open tasks are blocked.</span>
          ) : (
            <span className="text-muted-foreground">No open tasks.</span>
          )}
        </Fact>
        <Fact icon={<FlagIcon />} label="Next milestone">
          {report.nextMilestone ? (
            <>
              <span className="font-medium">{report.nextMilestone.title}</span>
              <span className="block text-xs text-muted-foreground">
                {report.nextMilestone.targetDate
                  ? `Target ${formatDay(report.nextMilestone.targetDate)}`
                  : "No target date yet"}
              </span>
            </>
          ) : (
            <span className="text-muted-foreground">No milestone planned.</span>
          )}
        </Fact>
        <Fact icon={<OctagonAlertIcon />} label="Current blockers">
          {report.blocked.length ? (
            <ul className="space-y-1">
              {report.blocked.slice(0, 3).map((t) => (
                <li key={t.id}>
                  <span className="font-medium">{t.title}</span>
                  <span className="block text-xs text-muted-foreground">
                    {t.blockedReason}
                  </span>
                </li>
              ))}
            </ul>
          ) : (
            <span className="text-muted-foreground">None recorded.</span>
          )}
        </Fact>
        <Fact icon={<CalendarClockIcon />} label="Deadlines">
          <span className={cn(report.overdue.length && "font-medium text-primary")}>
            {report.overdue.length} overdue
          </span>
          <span className="text-muted-foreground">
            {" "}
            · {report.dueSoon.length} due in 2 days · {report.completionPct}% of tasks
            done
          </span>
        </Fact>
      </dl>

      <div className="mt-auto flex flex-wrap gap-2 pt-6">
        {directive.href && directive.cta ? (
          <Button asChild className="font-semibold">
            <Link href={directive.href}>
              {directive.cta}
              <ArrowRightIcon />
            </Link>
          </Button>
        ) : null}
        {directive.href !== "/ceo" ? (
          <Button asChild variant="outline">
            <Link href="/ceo">Get orders from your AI CEO</Link>
          </Button>
        ) : null}
      </div>
    </section>
  )
}

function Fact({
  icon,
  label,
  children,
}: {
  icon: ReactNode
  label: string
  children: ReactNode
}) {
  return (
    <div className="min-w-0">
      <dt className="flex items-center gap-1.5 text-xs font-medium text-muted-foreground [&_svg]:size-3.5">
        {icon}
        {label}
      </dt>
      <dd className="mt-1 break-words">{children}</dd>
    </div>
  )
}
